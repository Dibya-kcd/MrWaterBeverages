const dictionaries: Record<LanguageCode, TranslationMap> = { en, or };

/**
 * Simple interpolation: replaces {{key}} with values from params.
 */
export function translate(
  language: LanguageCode,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = dictionaries[language] || dictionaries.en;
  let text = dict[key] ?? dictionaries.en[key] ?? key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`{{${k}}}`, 'g'), String(v));
    });
  }
  return text;
}

export function getAvailableLanguages(): { code: LanguageCode; label: string }[] {
  return (Object.keys(LANGUAGE_LABELS) as LanguageCode[]).map((code) => ({
    code,
    label: LANGUAGE_LABELS[code],
  }));
}
